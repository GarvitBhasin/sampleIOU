-- IOU relational schema. All money is stored as integer cents and weights as hundredths.
CREATE TABLE IF NOT EXISTS iou_users (
    username_key VARCHAR(20) PRIMARY KEY,
    username VARCHAR(20) NOT NULL,
    login_token_hash CHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS iou_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    group_code VARCHAR(6) NOT NULL UNIQUE,
    owner_username_key VARCHAR(20) NOT NULL REFERENCES iou_users(username_key),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS iou_group_members (
    group_id BIGINT NOT NULL REFERENCES iou_groups(id) ON DELETE CASCADE,
    member_order INTEGER NOT NULL CHECK (member_order >= 0),
    username_key VARCHAR(20) NOT NULL REFERENCES iou_users(username_key),
    display_name TEXT NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    has_left BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (group_id, member_order)
);

CREATE UNIQUE INDEX IF NOT EXISTS iou_one_current_membership_per_user
    ON iou_group_members(group_id, username_key) WHERE has_left = FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS iou_current_member_names_unique
    ON iou_group_members(group_id, LOWER(BTRIM(display_name))) WHERE has_left = FALSE;

CREATE INDEX IF NOT EXISTS iou_members_by_user
    ON iou_group_members(username_key, group_id) WHERE has_left = FALSE;

CREATE TABLE IF NOT EXISTS iou_bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES iou_groups(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    total_cents BIGINT NOT NULL CHECK (total_cents > 0),
    bill_owner_member_name TEXT NOT NULL,
    bill_owner_username_key VARCHAR(20) NOT NULL REFERENCES iou_users(username_key),
    bill_owner_member_order INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    suggested_date DATE,
    display_order INTEGER NOT NULL,
    UNIQUE (id, group_id),
    FOREIGN KEY (group_id, bill_owner_member_order)
        REFERENCES iou_group_members(group_id, member_order)
);

CREATE INDEX IF NOT EXISTS iou_bills_by_group
    ON iou_bills(group_id, display_order);

CREATE TABLE IF NOT EXISTS iou_bill_shares (
    bill_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    member_order INTEGER NOT NULL,
    weight_hundredths INTEGER NOT NULL CHECK (weight_hundredths BETWEEN 0 AND 100),
    share_cents BIGINT NOT NULL CHECK (share_cents >= 0),
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    confirmed_at TIMESTAMPTZ,
    PRIMARY KEY (bill_id, member_order),
    FOREIGN KEY (bill_id, group_id) REFERENCES iou_bills(id, group_id) ON DELETE CASCADE,
    FOREIGN KEY (group_id, member_order)
        REFERENCES iou_group_members(group_id, member_order)
);
